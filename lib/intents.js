// แยกว่าผู้ใช้ "อยากทำอะไร" จากคำพูดแบบไม่เป็นทางการ (ยกเลิก / แก้ไข / ลบข้อมูล / วิธีใช้)
// อยากให้บอทเข้าใจคำใหม่ เพิ่มคำที่นี่ แล้วเพิ่มเคสใน tests/intents.test.mjs

// คำลงท้าย/คำเสริมที่ไม่มีความหมาย ตัดทิ้งก่อนเช็ค เช่น "ยกเลิกเมื่อกี้หน่อยครับ" → "ยกเลิกเมื่อกี้"
const SOFT = /(ครับผม|ครับ|คับ|ค่ะ|คะ|ค้าบ|จ้า|จ้ะ|จ๊ะ|น้า|นะ|หน่อย|ให้ที|ด้วย|ได้ไหม|ได้มั้ย|ได้ป่าว|ได้ปะ|ได้เปล่า|ได้รึเปล่า|ได้หรือเปล่า|ไหม|มั้ย|เถอะ|อ่ะ|ฮะ|พอดี|เลย|\s|[!?.,~]+)/g;
export const squash = msg => String(msg).replace(SOFT, '');

const WHEN = '(เมื่อกี้|เมื่อกี๊|เมื่อกี|เมื่อตะกี้|ตะกี้|ตะกี๊|เมื่อสักครู่|ล่าสุด|อันล่าสุด|รายการล่าสุด|ที่แล้ว|ก่อนหน้า|อันนั้น|อันเมื่อกี้|ที่จด|ที่จดไป|ที่เพิ่งจด|ที่พึ่งจด|ที่บันทึก|ที่ส่งไป|ที่ส่ง)';
const UNDO_VERB = '(ยกเลิก|ลบ|ลบทิ้ง|เอาออก|ไม่เอา|ถอน|ย้อนกลับ|ยกเลิกการจด|cancel|undo)';

// ยกเลิกของที่เพิ่งจด: "ยกเลิก", "ยกเลิกเมื่อกี้", "ลบอันล่าสุด", "เมื่อกี้ไม่เอา", "จดซ้ำ"
const UNDO = new RegExp(`^${WHEN}?(ขอ)?${UNDO_VERB}(อัน|รายการ|ตัว)?${WHEN}?$|^(ลบล่าสุด|ยกเลิกล่าสุด)$|^(จด|บันทึก|ส่ง)ซ้ำ$`, 'i');
export function isUndo(msg) {
  const s = squash(msg);
  return s.length > 0 && s.length <= 30 && UNDO.test(s);
}

// อยากแก้ แต่ไม่ได้บอกว่าอันไหน: "แก้ไข", "พิมพ์ผิด", "ขอแก้ราคาได้ไหม", "ยอดผิด", "จดไม่ถูก"
export const EDIT_RE = /แก้|เปลี่ยน|พิมพ์ผิด|พิมผิด|จดผิด|ใส่ผิด|บันทึกผิด|กดผิด|ผิด|ไม่ถูก|ไม่ตรง|เพี้ยน|ลบ|เอาออก|ย้อนกลับ|ย้อน|undo|edit|ไม่ถูกต้อง|ผิดพลาด/i;
export function isEdit(msg) {
  const s = squash(msg);
  return s.length > 0 && s.length <= 40 && !/\d/.test(s) && EDIT_RE.test(s) && !/^ลบคำ/.test(s) && !/^ลบข้อมูล|^ลบบัญชี/.test(s);
}

// ตัดคำทั่วไปออกจากเป้าหมาย เหลือแต่สิ่งที่ระบุจริง: "ราคาได้ไหม" → "" , "ค่ากินวันที่12" → "ค่ากินวันที่12"
export function cleanTarget(s) {
  return squash(s)
    .replace(/^(ไขข้อมูล|ไข|ข้อมูล)/, '')
    .replace(/ราคา|ยอดเงิน|ยอด|จำนวนเงิน|จำนวน|ตัวเลข|เงิน|ชื่อ|หมวดหมู่|หมวด|รายการ|อันนี้|อันที่|อัน|ตัว|ให้|ใหม่|เมื่อกี้|เมื่อกี๊|เมื่อตะกี้|ตะกี้|ล่าสุด|ที่จด|ที่ผิด|ผิด|หน่อย/g, '')
    .trim();
}

export const WIPE_RE = /^(ลบข้อมูล(ของ)?(ฉัน|ผม|หนู|เรา|ทั้งหมด|ของฉัน)?|ลบบัญชี|ลบข้อมูลทั้งหมดของฉัน|ลบทุกอย่าง|ลบข้อมูลทั้งหมด)$/;
export const isWipe = msg => WIPE_RE.test(squash(msg));

export const HELP_RE = /^(วิธีใช้|ช่วย|ช่วยด้วย|help|\?|เมนู|ใช้ยังไง|ทำยังไง|ใช้ไง|ทำไง|งง|ไม่เข้าใจ|สอนหน่อย|สอน|คู่มือ|คำสั่ง)$/i;
export const isHelp = msg => HELP_RE.test(squash(msg)) || HELP_RE.test(String(msg).trim());
